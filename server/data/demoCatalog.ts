export function getDemoMediaDetail(tmdbId: number, mediaType: 'movie' | 'tv'): MediaDetail | null {
  const base =
    DEMO_MEDIA_CATALOG.find((item) => item.tmdbId === tmdbId && item.mediaType === mediaType) ??
    DEMO_MEDIA_CATALOG.find((item) => item.tmdbId === tmdbId);

  if (!base) return null;

  const related = DEMO_MEDIA_CATALOG.filter((m) => m.tmdbId !== base.tmdbId).slice(0, 6);

  return {
    ...base,
    runtime: mediaType === 'movie' ? 166 : 45,
    status: mediaType === 'movie' ? 'Lançado' : 'Em Exibição',
    tagline: 'Experiência cinematográfica em alta definição (Modo Demonstração)',
    director: mediaType === 'movie' ? 'Denis Villeneuve' : 'Jon Favreau',
    cast: [
      { id: 101, name: 'Elenco Principal 1', character: 'Protagonista', profilePath: null },
      { id: 102, name: 'Elenco Principal 2', character: 'Co-protagonista', profilePath: null },
      { id: 103, name: 'Elenco Principal 3', character: 'Antagonista', profilePath: null },
      { id: 104, name: 'Elenco Principal 4', character: 'Mentor', profilePath: null },
    ],
    videos: [],
    recommendations: related,
    similar: related.slice().reverse(),
    ...(mediaType === 'tv'
      ? {
          numberOfSeasons: 2,
          numberOfEpisodes: 16,
          seasons: [
            {
              id: 1,
              seasonNumber: 1,
              name: 'Temporada 1',
              overview: 'Temporada inicial da série com 8 episódios.',
              posterPath: base.posterPath,
              episodeCount: 8,
              airDate: base.releaseDate,
            },
            {
              id: 2,
              seasonNumber: 2,
              name: 'Temporada 2',
              overview: 'Segunda temporada expandindo o universo da trama.',
              posterPath: base.posterPath,
              episodeCount: 8,
              airDate: '2024-05-01',
            },
          ],
        }
      : {}),
  };
}

export function getDemoSeasonDetail(tmdbId: number, seasonNumber: number): SeasonDetail {
  const item = DEMO_MEDIA_CATALOG.find((m) => m.tmdbId === tmdbId);
  return {
    id: seasonNumber,
    seasonNumber,
    name: `Temporada ${seasonNumber}`,
    overview: `Episódios da Temporada ${seasonNumber} (Modo Demonstração).`,
    posterPath: item?.posterPath ?? HERO_DUNE_BACKDROP,
    episodeCount: 6,
    airDate: item?.releaseDate ?? '2024-01-01',
    episodes: Array.from({ length: 6 }, (_, idx) => ({
      id: seasonNumber * 100 + idx + 1,
      episodeNumber: idx + 1,
      seasonNumber,
      name: `Episódio ${idx + 1} — Capítulo ${idx + 1}`,
      overview: `Descrição do episódio ${idx + 1} da temporada ${seasonNumber} disponível ao conectar TMDB_ACCESS_TOKEN.`,
      stillPath: item?.backdropPath ?? HERO_DUNE_BACKDROP,
      runtime: 44 + (idx % 3) * 4,
      airDate: '2024-01-10',
      voteAverage: 8.2 + (idx % 4) * 0.1,
    })),
  };
}
